import type { Product } from '../types'

/**
 * В характеристиках товара явно указано крепление в 19"/13" стойку (или высота в юнитах) —
 * только по этому признаку решаем, физически ли он ставится в серверный шкаф. Категории
 * "роутер"/"коммутатор"/"прочее" смешивают и стоечные модели, и настольные пластиковые
 * коробочки (домашние роутеры, PoE-инжекторы, медиаконвертеры) — категория одна и та же,
 * а в шкаф едет только то, что реально можно закрепить на рейках.
 */
const RACK_MOUNT_HINT =
  /монтаж[а-я]*\s+в\s+стойку|монтируем[а-я]*\s+в\s+стойку|монтируется\s+в\s+стойку|установка\s+в\s+стойку|19["-]?\s*дюймов|13["-]?\s*дюймов|\b1U\b|\b2U\b|\b3U\b/i

/** Точки доступа и IP-камеры монтируются на стене/потолке объекта, а не в шкаф — независимо от текста характеристик. */
const NEVER_RACK_MOUNTABLE_CATEGORIES = new Set(['ap', 'camera'])

/** Физически монтируется ли товар в 19" серверный шкаф — по факту, а не по одной лишь категории. */
export function isRackMountable(product: Product): boolean {
  if (NEVER_RACK_MOUNTABLE_CATEGORIES.has(product.category)) return false
  const text = Object.values(product.specs).join(' ')
  return RACK_MOUNT_HINT.test(text)
}
